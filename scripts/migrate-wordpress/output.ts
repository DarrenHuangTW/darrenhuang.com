export function writeStory(options: {
  repoRoot: string;
  story: StoryManifestEntry;
  excerpt: string;
  poster: string | null;
  publishedAt: string;
  updatedAt: string;
  ampHtml: string;
  comparisonNotes: string[];
  omittedAssets: string[];
}): void {
  const storyDir = path.join(options.repoRoot, 'src', 'content', 'stories');
  const publicStoryDir = path.join(
    options.repoRoot,
    'public',
    'web-stories',
    options.story.slug,
  );
  mkdirSync(publicStoryDir, { recursive: true });

  writeFileSync(
    path.join(storyDir, `${options.story.slug}.json`),
    `${JSON.stringify(
      {
        aliases: options.story.aliases,
        ampSourcePath: `/web-stories/${options.story.slug}/story.html`,
        canonicalPath: options.story.canonicalPath,
        excerpt: options.excerpt,
        legacyComparison: {
          decision: options.story.comparisonDecision,
          notes: options.comparisonNotes,
          omittedAssets: options.omittedAssets,
        },
        legacyPageCount: options.story.legacyPageCount,
        legacyWpId: options.story.legacyWpId,
        modernPageCount: options.story.modernPageCount,
        modernWpId: options.story.modernWpId,
        poster: options.poster,
        publishedAt: options.publishedAt,
        slug: options.story.slug,
        sourceChecksum: options.story.sourceChecksum,
        artifactChecksum: options.story.artifactChecksum,
        title: options.story.title,
        transcript: options.story.transcript,
        updatedAt: options.updatedAt,
      },
      null,
      2,
    )}\n`,
    'utf8',
  );
  writeFileSync(
    path.join(publicStoryDir, 'story.html'),
    options.ampHtml.replaceAll('\r\n', '\n'),
    'utf8',
  );
}

export function writeAliasPage(options: {
  repoRoot: string;
  alias: string;
  canonicalPath: string;
  title: string;
}): void {
  const cleanAlias = options.alias.replace(/^\/+|\/+$/g, '');
  if (
    !cleanAlias ||
    cleanAlias.split('/').some((segment) => segment === '..')
  ) {
    throw new Error(`Unsafe alias path: ${options.alias}`);
  }

  const isHtmlAlias = cleanAlias.toLocaleLowerCase('en-US').endsWith('.html');
  const outputPath = isHtmlAlias
    ? path.join(options.repoRoot, 'public', ...cleanAlias.split('/'))
    : path.join(
        options.repoRoot,
        'public',
        ...cleanAlias.split('/'),
        'index.html',
      );
  mkdirSync(path.dirname(outputPath), { recursive: true });
  const escapedTitle = options.title
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');
  const canonicalTarget = path.resolve(
    options.repoRoot,
    'public',
    options.canonicalPath.replace(/^\//, ''),
  );
  const relativeTarget = path
    .relative(path.dirname(outputPath), canonicalTarget)
    .replaceAll('\\', '/');
  const navigationTarget = relativeTarget.startsWith('.')
    ? relativeTarget
    : `./${relativeTarget}`;
  const escapedNavigation = navigationTarget
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;');
  const escapedCanonical = `${PRODUCTION_SITE_URL}${options.canonicalPath}`
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;');
  const html = `<!doctype html>
<!-- Generated migration alias. -->
<html lang="zh-Hant">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width,initial-scale=1">
    <meta name="robots" content="noindex,follow">
    <meta http-equiv="refresh" content="0;url=${escapedNavigation}">
    <link rel="canonical" href="${escapedCanonical}">
    <title>${escapedTitle}｜數位引擎</title>
  </head>
  <body>
    <p>頁面已搬遷至 <a href="${escapedNavigation}">${escapedTitle}</a>。</p>
  </body>
</html>
`;
  writeFileSync(outputPath, html, 'utf8');
}

export function writeManifest(
  repoRoot: string,
  manifest: MigrationManifest,
): void {
  const migrationDir = path.join(repoRoot, 'migration');
  mkdirSync(migrationDir, { recursive: true });
  writeFileSync(
    path.join(migrationDir, 'manifest.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8',
  );
}
