export function sha256(value: string | Buffer): string {
  return createHash('sha256').update(value).digest('hex');
}

export async function fingerprintSource(
  filePath: string,
): Promise<SourceFingerprint> {
  const hash = createHash('sha256');
  const stream = createReadStream(filePath);
  for await (const chunk of stream) hash.update(chunk as Buffer);

  return {
    filename: path.basename(filePath),
    bytes: statSync(filePath).size,
    sha256: hash.digest('hex'),
  };
}

export function normalizedTextChecksum(html: string): string {
  const text = html
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/\s+/g, ' ')
    .normalize('NFC')
    .trim();

  return sha256(text);
}

function assertGeneratedDirectory(repoRoot: string, directory: string): void {
  const root = path.resolve(repoRoot);
  const target = path.resolve(directory);
  const allowed = [
    path.resolve(repoRoot, 'src', 'content', 'posts'),
    path.resolve(repoRoot, 'src', 'content', 'pages'),
    path.resolve(repoRoot, 'src', 'content', 'stories'),
    path.resolve(repoRoot, 'public', 'blog'),
    path.resolve(repoRoot, 'public', 'web-stories'),
  ];

  if (!target.startsWith(`${root}${path.sep}`) || !allowed.includes(target)) {
    throw new Error(
      `Refusing to replace unexpected generated directory: ${target}`,
    );
  }
}

export function resetGeneratedDirectory(
  repoRoot: string,
  directory: string,
): void {
  assertGeneratedDirectory(repoRoot, directory);
  if (existsSync(directory))
    rmSync(directory, { force: true, recursive: true });
  mkdirSync(directory, { recursive: true });
}

export function removePreviousRootAliasPages(repoRoot: string): void {
  const manifestPath = path.join(repoRoot, 'migration', 'manifest.json');
  if (!existsSync(manifestPath)) return;

  const previous = JSON.parse(readFileSync(manifestPath, 'utf8')) as {
    posts?: Array<{ aliases?: unknown }>;
    pages?: Array<{ aliases?: unknown }>;
    stories?: Array<{ aliases?: unknown }>;
  };
  const entries = [
    ...(previous.posts ?? []),
    ...(previous.pages ?? []),
    ...(previous.stories ?? []),
  ];

  for (const entry of entries) {
    if (!Array.isArray(entry.aliases)) continue;
    for (const alias of entry.aliases) {
      if (typeof alias !== 'string' || !/^\/[^/]+\.html$/i.test(alias))
        continue;
      const target = path.resolve(repoRoot, 'public', alias.slice(1));
      const publicRoot = path.resolve(repoRoot, 'public');
      if (!target.startsWith(`${publicRoot}${path.sep}`) || !existsSync(target))
        continue;
      const source = readFileSync(target, 'utf8');
      if (source.includes('<!-- Generated migration alias. -->'))
        rmSync(target);
    }
  }
}

function writeGeneratedMarkdown(
  filePath: string,
  frontmatter: Record<string, unknown>,
  html: string,
): void {
  const notice =
    '<!-- Generated by scripts/migrate-wordpress. Do not edit by hand. -->';
  const rendered = matter.stringify(
    `${notice}\n\n${html.trim()}\n`,
    frontmatter,
  );
  writeFileSync(filePath, rendered.replaceAll('\r\n', '\n'), 'utf8');
}

export function writePost(options: {
  repoRoot: string;
  manifest: PostManifestEntry;
  excerpt: string;
  html: string;
}): void {
  const postDir = path.join(options.repoRoot, 'src', 'content', 'posts');
  const { manifest } = options;
  writeGeneratedMarkdown(
    path.join(postDir, `${manifest.slug}.md`),
    {
      aliases: manifest.aliases,
      canonicalPath: manifest.canonicalPath,
      categories: manifest.categories,
      excerpt: options.excerpt,
      featuredMedia: manifest.featuredMedia,
      originalStatus: manifest.originalStatus,
      publishedAt: manifest.publishedAt,
      slug: manifest.slug,
      sourceChecksum: manifest.sourceChecksum,
      tags: manifest.tags,
      title: manifest.title,
      updatedAt: manifest.updatedAt,
      wasMembersOnly: manifest.wasMembersOnly,
      wpId: manifest.wpId,
    },
    options.html,
  );
}

